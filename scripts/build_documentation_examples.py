"""Keep compact, silent evidence clips for the project write-up."""

import csv
import json
import shutil
from pathlib import Path

import cv2
import imageio.v2 as imageio


ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "documentation" / "evidence"


def _rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines()]


def _annotated_excerpt(source: Path, tracks: list[tuple[str, Path]],
                       start_frame: int, end_frame: int, output: Path) -> None:
    records = [(label, _rows(ROOT / trajectory)) for label, trajectory in tracks]
    capture = cv2.VideoCapture(str(ROOT / source))
    if not capture.isOpened():
        raise ValueError(f"Cannot open {source}")
    fps = capture.get(cv2.CAP_PROP_FPS) or 24
    capture.set(cv2.CAP_PROP_POS_FRAMES, start_frame)
    writer = imageio.get_writer(output, fps=fps, codec="libx264", quality=7,
                                macro_block_size=2)
    try:
        for index in range(start_frame, end_frame + 1):
            ok, frame = capture.read()
            if not ok:
                raise ValueError(f"Video ended before frame {index}: {source}")
            frame = cv2.resize(frame, (960, 540), interpolation=cv2.INTER_AREA)
            cv2.rectangle(frame, (0, 0), (960, 48 + 34 * len(records)), (15, 15, 15), -1)
            cv2.putText(frame, f"frame {index} | visible marker IDs: " +
                        ", ".join(str(value) for value in records[0][1][index]["visible_ids"]),
                        (18, 32), cv2.FONT_HERSHEY_SIMPLEX, .72, (255, 255, 255), 2)
            for offset, (label, rows) in enumerate(records):
                row = rows[index]
                status = row["quality"]
                source_id = row.get("usb_pose_source")
                if source_id:
                    status += f" via {source_id}"
                colour = (110, 240, 110) if row["quality"] == "ok" else (95, 110, 250)
                cv2.putText(frame, f"{label}: {status}", (18, 68 + offset * 34),
                            cv2.FONT_HERSHEY_SIMPLEX, .72, colour, 2)
            writer.append_data(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
    finally:
        writer.close()
        capture.release()


def main() -> None:
    DEST.mkdir(parents=True, exist_ok=True)
    copies = {
        "single_marker_before_pose_prior.mp4":
            "outputs/video_evaluation/20mm_10102026_194658/replay/replay.mp4",
        "single_marker_after_pose_prior.mp4":
            "outputs/video_evaluation_pose_prior/20mm_10102026_194658/replay/replay.mp4",
        "new_batch_marker0_only.mp4":
            "outputs/dual_marker_original_mount/marker0_only/10112026_194839/replay/replay.mp4",
        "new_batch_two_markers.mp4":
            "outputs/dual_marker_original_mount/dual/10112026_194839/replay/replay.mp4",
        "dual_194811_depth_entry.mp4":
            "outputs/dual_marker_original_mount/dual/10112026_194811/replay/replay.mp4",
    }
    for name, source in copies.items():
        shutil.copy2(ROOT / source, DEST / name)
    _annotated_excerpt(
        Path("video_data/20mm_marker/10102026_194658.mov"),
        [("marker 0 only", Path("outputs/video_evaluation_pose_prior/20mm_10102026_194658/tracking/trajectory.jsonl"))],
        24, 78, DEST / "single_marker_tracking_gap.mp4")
    _annotated_excerpt(
        Path("video_data/double_marker_original_mount/10112026_194713.mov"),
        [("marker 0 only", Path("outputs/dual_marker_original_mount/marker0_only/10112026_194713/tracking/trajectory.jsonl")),
         ("markers 0 + 10", Path("outputs/dual_marker_original_mount/dual/10112026_194713/tracking/trajectory.jsonl"))],
        55, 110, DEST / "dual_marker_visibility.mp4")
    manifest = {
        "format": "local documentation clips; MP4 video only, no audio",
        "original_files_unchanged": True,
        "before_after_source": "10102026_194658.mov",
        "pose_prior_effect": "Old replay needed 360 controller steps; pose-prior replay needed 95. Tracking gap remains masked.",
        "dual_visibility_source": "10112026_194713.mov",
        "new_batch_replay_source": "10112026_194839.mov",
        "depth_entry_example_source": "10112026_194811.mov",
        "clips": {name: source for name, source in copies.items()},
        "single_marker_tracking_gap_frames": [24, 78],
        "dual_marker_visibility_frames": [55, 110],
        "scripted_reference": "scripted_12mm_success.mp4 (generated by mimicvla sim-demo)",
    }
    (DEST / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    with (ROOT / "outputs/datasets/usb_marker_raw/quality_review.csv").open(newline="") as stream:
        quality_rows = list(csv.DictReader(stream))
    selected = [row for row in quality_rows
                if row["episode_id"].startswith("12mm_")
                or row["episode_id"].endswith(("194648", "194658"))]
    with (DEST / "quality_examples.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=quality_rows[0].keys())
        writer.writeheader()
        writer.writerows(selected)
    score_dir = ROOT / "outputs/evaluation_depth_entry_12mm"
    for name in ("summary.json", "results.csv"):
        shutil.copy2(score_dir / name, DEST / f"insertion_depth_entry_12mm_{name}")
    print(f"Preserved {len(list(DEST.glob('*.mp4')))} clips in {DEST}")


if __name__ == "__main__":
    main()
